"""Phase 0: inspect the raw data root and write the data report and manifest.

    python scripts/data_report.py [--config configs/data.yaml] [--max-cases N]

Outputs (the raw root is never written to):
    data/file_inventory.csv   one row per NIfTI file (header, checksum, intensities)
    data/manifest.csv         one row per case
    data/phase0_summary.json  machine check, counts and data situation
    docs/data_report.md       human-readable report
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from collections import Counter
from pathlib import Path

import pandas as pd

from btqc.config import REPO_ROOT, load_config, raw_root, resolve
from btqc.data.discover import SEQUENCES, discover
from btqc.data.manifest import (
    build_case_table,
    build_inventory,
    find_institution_tables,
    load_institution_table,
)
from btqc.sysinfo import machine_report


def data_situation(n_cases: int, n_seg: int, has_institutions: bool) -> tuple[str, str]:
    if n_cases == 0:
        return "C", "no complete cases found"
    if n_seg == 0:
        return "C", "only unlabeled scans: no segmentation files found"
    if not has_institutions:
        return "B", "labeled data without an institution table"
    return "A", "labeled data with institution labels"


def _fmt_counter(c: Counter[str] | dict[str, int]) -> str:
    return ", ".join(f"`{k}`: {v}" for k, v in sorted(c.items(), key=lambda kv: -kv[1])) or "none"


def _range(s: pd.Series) -> str:
    s = pd.to_numeric(s, errors="coerce").dropna()
    if s.empty:
        return "n/a"
    return f"{s.min():.4g} / {s.median():.4g} / {s.max():.4g}"


def write_report(path: Path, ctx: dict, files: pd.DataFrame, cases: pd.DataFrame) -> None:
    m = ctx["machine"]
    gpus = ", ".join(f"{g['name']} ({g['memory_gb']} GB)" for g in m["gpus"]) or "none"
    L: list[str] = []
    a = L.append
    a("# Data report (Phase 0)")
    a("")
    a(f"Generated by `scripts/data_report.py` on {ctx['generated']} from `{ctx['raw_root']}` (read-only).")
    a("")
    a(f"**Data situation: {ctx['situation']}** ({ctx['situation_reason']}).  ")
    a(f"**Compute tier: {m['compute_tier']}** ({m['compute_tier_reason']}).")
    a("")
    a("> Research prototype only. Not a medical device and not for diagnosis.")
    a("")
    a("## 1. Machine")
    a("")
    a("| Item | Value |")
    a("|---|---|")
    a(f"| OS | {m['os']} |")
    a(f"| CPU | {m['cpu']} ({m['cpu_logical_cores']} logical cores) |")
    a(f"| RAM | {m['ram_gb']} GB |")
    a(f"| Free disk (repo drive) | {m['disk_free_gb']} GB |")
    a(f"| GPU (nvidia-smi) | {gpus} |")
    a(f"| Python | {m['python']} |")
    t = m["torch"]
    a(f"| torch | {t.get('version', 'not installed')}, CUDA available: {t.get('cuda_available')} |")
    a(f"| Network | {'reachable' if m['network'] else 'not reachable'} |")
    a("")
    a("## 2. Directory contents")
    a("")
    a(f"- NIfTI files parsed: {ctx['n_nifti']} in {ctx['n_cases']} cases.")
    a(f"- Unparsed NIfTI files: {len(ctx['unparsed'])}.")
    for u in ctx["unparsed"][:50]:
        a(f"  - `{u}`")
    a(f"- Sequence conflicts (wrapper vs inner name): {len(ctx['conflicts'])}.")
    for c in ctx["conflicts"][:50]:
        a(f"  - {c}")
    a(f"- Duplicate files for the same case and sequence: {len(ctx['duplicates'])}.")
    a(f"- Other files by extension: {_fmt_counter(ctx['other_files'])}.")
    a(f"- Files by sequence: {_fmt_counter(Counter(files['sequence']))}.")
    a(f"- Layout: {ctx['layout_note']}")
    a(f"- Inner file-name patterns: {_fmt_counter(ctx['inner_patterns'])}.")
    a("- Searched for documents (`.csv .json .txt .docx .pdf .html`) inside the raw root: "
      f"{_fmt_counter(ctx['docs_in_root']) if ctx['docs_in_root'] else 'none found'}.")
    a("")
    a("## 3. Headers")
    a("")
    a("| Property | Values (count of files) |")
    a("|---|---|")
    for col, label in [("shape", "Shape"), ("dtype", "dtype"), ("spacing", "Voxel spacing (mm)"),
                       ("axcodes", "Orientation (nib.aff2axcodes)"), ("sform_code", "sform code"),
                       ("qform_code", "qform code"), ("scl_slope", "scl_slope"), ("scl_inter", "scl_inter")]:
        vals = Counter(str(tuple(v)) if isinstance(v, list | tuple) else str(v) for v in files[col])
        a(f"| {label} | {_fmt_counter(vals)} |")
    aff = Counter(json.dumps(v) for v in files["affine"])
    a(f"| Distinct affines | {len(aff)} |")
    a("")
    a("Most common affine:")
    a("")
    a("```")
    for row in json.loads(aff.most_common(1)[0][0]):
        a("  ".join(f"{x:9.3f}" for x in row))
    a("```")
    a("")
    ft = Counter(k for v in files["free_text_nonempty"] for k in v)
    a(f"Free-text header fields that were non-empty (`descrip`, `aux_file`, `db_name`, `intent_name`): "
      f"{_fmt_counter(ft) if ft else 'none'}. Their contents are not copied to any output.")
    a("")
    a("## 4. Case checks")
    a("")
    ok = cases[(cases["n_sequences"] == 4) & cases["grid_ok"] & (cases["problems"] == "")]
    a(f"- Cases with all four sequences, identical shape and affine: {len(ok)} of {len(cases)}.")
    bad = cases[cases["problems"] != ""]
    a(f"- Cases with problems: {len(bad)}.")
    for _, r in bad.head(50).iterrows():
        a(f"  - `{r['case_id']}`: {r['problems']}")
    a(f"- Cases with a segmentation file: {int(cases['has_seg'].sum())}.")
    a("")
    a("## 5. Intensities")
    a("")
    a("Min / median / max over cases of each per-file statistic (percentiles of nonzero voxels).")
    a("")
    a("| Sequence | min value | max value | p1 (nz) | p50 (nz) | p99 (nz) | nonzero fraction | border zero fraction |")
    a("|---|---|---|---|---|---|---|---|")
    for s in SEQUENCES:
        g = files[files["sequence"] == s]
        a(f"| {s} | {_range(g['min'])} | {_range(g['max'])} | {_range(g['p1_nz'])} | {_range(g['p50_nz'])} | "
          f"{_range(g['p99_nz'])} | {_range(g['nonzero_frac'])} | {_range(g['border_zero_frac'])} |")
    a("")
    a(f"Negative voxels present in {int((files['neg_frac'] > 0).sum())} files.")
    a(f"Skull-stripping check: {ctx['skull_note']}")
    a("")
    a("## 6. Segmentations and label convention")
    a("")
    if ctx["n_seg"] == 0:
        a("No segmentation files were found. The label convention (1/2/4 or 1/2/3) cannot be determined from "
          "this data; the pipeline supports both and is tested on synthetic fixtures.")
    else:
        a(f"Label values found: {ctx['label_values']}. Convention: **{ctx['label_convention']}**.")
    a("")
    a("## 7. Institution table")
    a("")
    if ctx["institution_table"]:
        a(f"Joined `{ctx['institution_table']}`: {ctx['n_with_institution']} cases have an institution.")
    else:
        a("No subject-to-institution table was found (searched the raw root and the configured folders for CSV "
          "files whose name contains partition, institution, site or mapping). **No site labels were invented.**")
        a("")
        a("Needed for the site-held-out protocol: the FeTS 2022 partitioning CSV that maps every training "
          "`Subject_ID` to a `Partition_ID` (institution), distributed with the FeTS 2022 challenge "
          "(`partitioning_1.csv`, natural partitioning by institution), together with the labeled FeTS 2022 / "
          "BraTS 2021 training data (registration on Synapse required). Set `institution_table` in "
          "`configs/data.yaml` to its path.")
    a("")
    a("## 8. Data situation and consequences")
    a("")
    a(f"**Situation {ctx['situation']}.** {ctx['situation_reason']}.")
    a("")
    if ctx["situation"] == "C":
        a("- The full pipeline (conversion, nnU-Net dataset preparation, harness, uncertainty, trust gate, API, "
          "dashboard, tests) is built and tested against synthetic fixtures and these unlabeled scans.")
        a("- No model is trained on real data and no accuracy number is reported. These cases are used for "
          "inference demos and the interface only, never for training or scoring.")
        a("- To run the experiments, obtain the labeled FeTS 2022 training data (1,251 cases expected) and the "
          "partitioning CSV described in section 7.")
    a("")
    notes = path.parent / "data_report_notes.md"
    if notes.exists():
        L.append(notes.read_text(encoding="utf-8"))
    path.write_text("\n".join(L) + "\n", encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--config", default="data")
    ap.add_argument("--max-cases", type=int, default=None)
    ap.add_argument("--workers", type=int, default=None)
    ap.add_argument("--no-network", action="store_true")
    args = ap.parse_args(argv)

    cfg = load_config(args.config)
    root = raw_root(cfg)
    if not root.is_dir():
        print(f"raw root not found: {root}", file=sys.stderr)
        return 2
    t0 = time.time()
    machine = machine_report(REPO_ROOT, check_network=not args.no_network)
    print(f"compute tier {machine['compute_tier']}: {machine['compute_tier_reason']}")

    disc = discover(root)
    n_nifti = sum(len(c.files) for c in disc.cases.values())
    print(f"discovered {n_nifti} NIfTI files in {len(disc.cases)} cases; unparsed {len(disc.unparsed)}")

    def prog(i: int, n: int) -> None:
        if i % 40 == 0 or i == n:
            print(f"  inspected {i}/{n} files ({time.time() - t0:.0f}s)", flush=True)

    files = build_inventory(disc, workers=args.workers or cfg.get("workers", 4), max_cases=args.max_cases,
                            progress=prog)

    tables = []
    if cfg.get("institution_table"):
        tables = [resolve(cfg["institution_table"])]
    else:
        tables = find_institution_tables(root, [resolve(d) for d in cfg.get("institution_search_dirs", [])])
    inst = None
    inst_path = None
    for tpath in tables:
        try:
            inst = load_institution_table(tpath)
            inst_path = tpath
            break
        except (ValueError, OSError) as e:
            print(f"ignored candidate table {tpath}: {e}")
    cases = build_case_table(files, inst)

    seg_files = files[files["sequence"] == "seg"]
    label_values: set[int] = set()
    for v in seg_files.get("unique_values", pd.Series(dtype=object)).dropna():
        label_values |= {int(k) for k in json.loads(v)}
    from btqc.data.labels import detect_convention

    conv = detect_convention(label_values) if label_values else "unknown"
    n_inst = int(cases["institution"].notna().sum()) if inst is not None else 0
    sit, why = data_situation(len(cases), len(seg_files), n_inst > 0)

    inner = Counter()
    for v in files["inner_name"].dropna():
        stem = str(v)
        inner["<8 digits>_brain_<seq>.nii" if "_brain_" in stem else
              ("FeTS2022_<id>_<seq>.nii" if stem.startswith("FeTS2022_") else "other")] += 1
    wrapped = int(files["inner_name"].notna().sum())
    layout = (f"{wrapped} of {len(files)} files sit inside a wrapper directory named like the file "
              "(e.g. `FeTS2022_00027/FeTS2022_00027_flair.nii/00000019_brain_flair.nii`); the wrapper name is "
              "used as the declared identity.") if wrapped else "flat files."
    docs = Counter(p.suffix.lower() for p in root.rglob("*")
                   if p.is_file() and p.suffix.lower() in {".csv", ".json", ".txt", ".docx", ".pdf", ".html"})
    bz = pd.to_numeric(files["border_zero_frac"], errors="coerce")
    nzf = pd.to_numeric(files["nonzero_frac"], errors="coerce")
    skull = (f"median border-shell zero fraction {bz.median():.4f} (min {bz.min():.4f}); median nonzero fraction "
             f"{nzf.median():.3f}. A large exactly-zero background consistent with skull-stripped volumes is "
             f"{'present' if bz.median() > 0.99 and nzf.median() < 0.3 else 'NOT clearly present'}.")

    ctx = {
        "generated": time.strftime("%Y-%m-%d %H:%M"),
        "raw_root": str(root),
        "machine": machine,
        "n_nifti": n_nifti,
        "n_cases": len(disc.cases),
        "unparsed": [str(p.relative_to(root)) for p in disc.unparsed],
        "conflicts": disc.conflicts,
        "duplicates": disc.duplicates,
        "other_files": disc.other_files,
        "layout_note": layout,
        "inner_patterns": dict(inner),
        "docs_in_root": dict(docs),
        "skull_note": skull,
        "n_seg": len(seg_files),
        "label_values": sorted(label_values),
        "label_convention": conv,
        "institution_table": str(inst_path) if inst_path else None,
        "n_with_institution": n_inst,
        "situation": sit,
        "situation_reason": why,
        "elapsed_s": round(time.time() - t0, 1),
    }
    out_files = resolve(cfg["file_inventory"])
    out_cases = resolve(cfg["manifest"])
    out_files.parent.mkdir(parents=True, exist_ok=True)
    files.to_csv(out_files, index=False)
    cases.to_csv(out_cases, index=False)
    summary_path = out_cases.parent / "phase0_summary.json"
    summary_path.write_text(json.dumps(ctx, indent=2, default=str), encoding="utf-8")
    report = REPO_ROOT / "docs" / "data_report.md"
    report.parent.mkdir(parents=True, exist_ok=True)
    write_report(report, ctx, files, cases)
    print(f"situation {sit}: {why}")
    print(f"wrote {out_files}, {out_cases}, {summary_path}, {report} in {ctx['elapsed_s']} s")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
